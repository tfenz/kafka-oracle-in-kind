#!/bin/bash
# Runs once, right after the database has been created (mounted at /opt/oracle/scripts/setup).
# Prepares the database for log-based CDC (Debezium / OpenLogReplicator):
#   - ARCHIVELOG mode with archives in a FRA on the shared oradata volume
#   - FORCE LOGGING + minimal database-level supplemental logging
#   - a small DEMO schema in the PDB to replicate
# NOTE: this file is *sourced* by runUserScripts.sh -> no `exit`, no `set -e`.

FRA_DIR=/opt/oracle/oradata/fast_recovery_area
mkdir -p "${FRA_DIR}"

echo "### [cdc-prep] configuring recovery area"
sqlplus -s / as sysdba <<EOF
ALTER SYSTEM SET db_recovery_file_dest_size = 20G SCOPE=BOTH;
ALTER SYSTEM SET db_recovery_file_dest = '${FRA_DIR}' SCOPE=BOTH;
EOF

LOG_MODE=$(sqlplus -s / as sysdba <<'EOF'
SET HEADING OFF FEEDBACK OFF PAGESIZE 0
SELECT log_mode FROM v$database;
EOF
)
LOG_MODE=$(echo "${LOG_MODE}" | tr -d '[:space:]')
echo "### [cdc-prep] current log_mode: ${LOG_MODE}"

if [[ "${LOG_MODE}" != "ARCHIVELOG" ]]; then
  echo "### [cdc-prep] switching database to ARCHIVELOG (restart)"
  sqlplus -s / as sysdba <<'EOF'
SHUTDOWN IMMEDIATE
STARTUP MOUNT
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER PLUGGABLE DATABASE ALL OPEN;
ALTER PLUGGABLE DATABASE ALL SAVE STATE;
EOF
fi

echo "### [cdc-prep] enabling force logging, supplemental logging, demo schema"
sqlplus -s / as sysdba <<EOF
ALTER DATABASE FORCE LOGGING;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;
ALTER SYSTEM SWITCH LOGFILE;

ALTER SESSION SET CONTAINER = ${ORACLE_PDB};
CREATE USER demo IDENTIFIED BY "${DEMO_PWD:-demo}" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO demo;
CREATE TABLE demo.customers (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR2(100) NOT NULL,
  email      VARCHAR2(200),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);
INSERT INTO demo.customers (name, email) VALUES ('Alice', 'alice@example.com');
INSERT INTO demo.customers (name, email) VALUES ('Bob', 'bob@example.com');
COMMIT;

ALTER SESSION SET CONTAINER = CDB\$ROOT;
SELECT log_mode, force_logging, supplemental_log_data_min FROM v\$database;
EOF
echo "### [cdc-prep] done"
